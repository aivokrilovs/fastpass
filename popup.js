let backupMode = null; // null | 'export' | 'import'

// Show status notification
function showStatus(message, isError = false) {
  if (statusTimer) clearTimeout(statusTimer);
  statusMsg.textContent = message;
  statusMsg.className = isError ? 'status-error' : 'status-success';
  statusMsg.style.display = 'block';
  statusTimer = setTimeout(() => {
    statusMsg.style.display = 'none';
    statusTimer = null;
  }, 3500);
}

// Copy text to clipboard with temporary feedback
async function copyToClipboard(text, buttonEl, successText = 'Copied!') {
  try {
    await navigator.clipboard.writeText(text);
    const originalText = buttonEl.textContent;
    buttonEl.textContent = successText;
    buttonEl.disabled = true;
    setTimeout(() => {
      buttonEl.textContent = originalText;
      buttonEl.disabled = false;
    }, 1500);
  } catch (err) {
    console.error('Clipboard copy failed:', err);
  }
}

// Format 6-digit TOTP code with a space (e.g. "123 456")
function formatTotpCode(code) {
  if (!code || code.length !== 6) return code || '------';
  return `${code.slice(0, 3)} ${code.slice(3)}`;
}

// Safe inline delete confirmation (2 clicks)
function attachConfirmDelete(button, onConfirm) {
  let pending = false;
  let resetTimer = null;

  button.addEventListener('click', (e) => {
    e.stopPropagation();
    if (!pending) {
      pending = true;
      button.dataset.origText = button.textContent;
      button.textContent = 'Confirm?';
      button.classList.add('btn-confirm-delete');
      resetTimer = setTimeout(() => {
        pending = false;
        button.textContent = button.dataset.origText || 'Delete';
        button.classList.remove('btn-confirm-delete');
      }, 3000);
    } else {
      clearTimeout(resetTimer);
      pending = false;
      button.textContent = 'Deleting...';
      button.disabled = true;
      button.classList.remove('btn-confirm-delete');
      onConfirm();
    }
  });
}

// Helper to escape HTML characters
function escapeHtml(str) {
  if (!str) return '';
  return str.replace(/[&<>"']/g, (m) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  }[m]));
}

// Reorder a credential by one position (UI up/down → reversed in storage)
function reorderEntry(id, uiDirection) {
  // Storage is oldest→newest; display is reversed → flip direction
  const storageDirection = uiDirection === 'up' ? 'down' : 'up';
  chrome.runtime.sendMessage({
    action: 'REORDER_CREDENTIAL',
    payload: { id, direction: storageDirection }
  }, (response) => {
    if (chrome.runtime.lastError || !response?.success) return;
    loadSavedCredentials();
  });
}

// Render credentials list
function renderCredentials(credentials) {
  savedCredentials = credentials || [];
  // Codes were just generated by the worker, so they belong to the current window
  const windowStart = Math.floor(Date.now() / 30000);
  for (const cred of savedCredentials) cred.totpWindow = windowStart;
  savedTitle.textContent = `Saved Passwords (${savedCredentials.length})`;
  credentialsList.innerHTML = '';

  if (savedCredentials.length === 0) {
    credentialsList.innerHTML = '<div class="empty-state">No saved passwords</div>';
    return;
  }

  savedCredentials.forEach((cred, displayIdx) => {
    const isFirst = displayIdx === 0;
    const isLast = displayIdx === savedCredentials.length - 1;

    const wrapper = document.createElement('div');
    wrapper.style.cssText = 'position:relative;display:flex;align-items:center;margin-bottom:8px;';

    const card = document.createElement('div');
    card.className = 'card';
    card.dataset.id = cred.id;
    card.style.marginBottom = '0';
    card.style.flex = '1';

    card.innerHTML = `
      <div class="card-row">
        <span class="label">Domain</span>
        <span class="value" style="font-weight: 700;">${escapeHtml(cred.hostname)}</span>
      </div>
      <div class="card-row">
        <span class="label">Username</span>
        <span class="value">${escapeHtml(cred.username || '(none)')}</span>
      </div>
      <div class="card-row">
        <span class="label">Password</span>
        ${cred.decryptError ? '<span class="value" style="color: var(--danger-text);">Decryption failed</span>' : cred.password ? `
        <div style="display: flex; align-items: center; gap: 6px;">
          <span class="value pass-display" data-hidden="true">••••••••</span>
          <button type="button" class="btn toggle-pass-btn">Show</button>
          <button type="button" class="btn copy-pass-btn">Copy</button>
        </div>
        ` : '<span class="value" style="color: var(--text-muted);">(none)</span>'}
      </div>
      ${cred.hasTotp && !cred.decryptError ? `
      <div class="totp-box">
        <div>
          <span class="totp-label">TOTP Code</span>
          <div class="totp-code">${formatTotpCode(cred.totpCode)}</div>
        </div>
        <div style="display: flex; align-items: center; gap: 6px;">
          <span class="totp-timer">${cred.totpRemaining || 30}s</span>
          <button type="button" class="btn show-secret-btn">Secret</button>
          <button type="button" class="btn copy-totp-btn">Copy TOTP</button>
        </div>
      </div>
      <div class="totp-secret-row" style="display:none; margin-top:4px; font-family:monospace; font-size:11px; word-break:break-all; color:var(--text-secondary);"></div>
      ` : ''}
      <div class="card-row" style="margin-top: 8px; justify-content: flex-end;">
        <button type="button" class="btn btn-danger delete-btn">Delete</button>
      </div>
    `;

    // Reorder arrows (overlaid to the right of the card, so they don't affect its width)
    const arrows = document.createElement('div');
    arrows.style.cssText = 'position:absolute;right:-13px;top:50%;transform:translateY(-50%);display:flex;flex-direction:column;align-items:center;gap:1px;';
    if (!isFirst) {
      const up = document.createElement('span');
      up.textContent = '▲';
      up.title = 'Move up';
      up.style.cssText = 'cursor:pointer;font-size:10px;color:var(--text-muted);line-height:1;user-select:none;';
      up.addEventListener('mouseenter', () => up.style.color = 'var(--text)');
      up.addEventListener('mouseleave', () => up.style.color = 'var(--text-muted)');
      up.addEventListener('click', () => reorderEntry(cred.id, 'up'));
      arrows.appendChild(up);
    }
    if (!isLast) {
      const dn = document.createElement('span');
      dn.textContent = '▼';
      dn.title = 'Move down';
      dn.style.cssText = 'cursor:pointer;font-size:10px;color:var(--text-muted);line-height:1;user-select:none;';
      dn.addEventListener('mouseenter', () => dn.style.color = 'var(--text)');
      dn.addEventListener('mouseleave', () => dn.style.color = 'var(--text-muted)');
      dn.addEventListener('click', () => reorderEntry(cred.id, 'down'));
      arrows.appendChild(dn);
    }


    // Toggle password reveal
    const passDisplay = card.querySelector('.pass-display');
    const togglePassBtn = card.querySelector('.toggle-pass-btn');
    if (togglePassBtn && passDisplay) {
      togglePassBtn.addEventListener('click', () => {
        const isHidden = passDisplay.dataset.hidden === 'true';
        if (isHidden) {
          passDisplay.textContent = cred.password;
          passDisplay.dataset.hidden = 'false';
          togglePassBtn.textContent = 'Hide';
        } else {
          passDisplay.textContent = '••••••••';
          passDisplay.dataset.hidden = 'true';
          togglePassBtn.textContent = 'Show';
        }
      });
    }

    // Copy password
    const copyPassBtn = card.querySelector('.copy-pass-btn');
    if (copyPassBtn) {
      copyPassBtn.addEventListener('click', () => {
        copyToClipboard(cred.password, copyPassBtn);
      });
    }

    // Copy TOTP
    const copyTotpBtn = card.querySelector('.copy-totp-btn');
    if (copyTotpBtn) {
      copyTotpBtn.addEventListener('click', () => {
        const currentCode = (cred.totpCode || '').replace(/\s+/g, '');
        copyToClipboard(currentCode, copyTotpBtn, 'Copied!');
      });
    }

    // Show/hide TOTP secret
    const showSecretBtn = card.querySelector('.show-secret-btn');
    const secretRow = card.querySelector('.totp-secret-row');
    if (showSecretBtn && secretRow) {
      showSecretBtn.addEventListener('click', () => {
        const visible = secretRow.style.display !== 'none';
        if (visible) {
          secretRow.style.display = 'none';
          secretRow.textContent = '';
          showSecretBtn.textContent = 'Secret';
        } else {
          secretRow.textContent = cred.totpSecret || '';
          secretRow.style.display = 'block';
          showSecretBtn.textContent = 'Hide';
        }
      });
    }

    // Delete credential
    const deleteBtn = card.querySelector('.delete-btn');
    attachConfirmDelete(deleteBtn, () => {
      chrome.runtime.sendMessage({
        action: 'DELETE_CREDENTIAL',
        payload: { id: cred.id }
      }, (response) => {
        if (chrome.runtime.lastError || !response?.success) {
          showStatus(chrome.runtime.lastError?.message || response?.error || 'Failed to delete credential.', true);
          deleteBtn.disabled = false;
          deleteBtn.textContent = 'Delete';
          return;
        }
        loadSavedCredentials();
        showStatus('Credential deleted.');
      });
    });

    credentialsList.appendChild(wrapper);
    wrapper.appendChild(card);
    wrapper.appendChild(arrows);
  });
}

// Find a rendered card by credential id (set via dataset, never via HTML)
function findCard(id) {
  return credentialsList.querySelector(`[data-id="${CSS.escape(id)}"]`) || null;
}

// Re-request codes from the service worker when the 30s window rolls over
function refreshTotpCodes() {
  chrome.runtime.sendMessage({ action: 'REFRESH_TOTP' }, (res) => {
    if (chrome.runtime.lastError || !res || !res.success) return;
    for (const fresh of res.codes) {
      const item = savedCredentials.find(c => c.id === fresh.id);
      if (!item) continue;
      item.totpCode = fresh.totpCode;
      item.totpWindow = Math.floor(Date.now() / 30000);
      const codeEl = findCard(item.id)?.querySelector('.totp-code');
      if (codeEl) codeEl.textContent = formatTotpCode(fresh.totpCode);
    }
  });
}

// Start live 1-second TOTP updater
function startTotpLiveUpdater() {
  if (activeTotpInterval) {
    clearInterval(activeTotpInterval);
    activeTotpInterval = null;
  }

  if (!savedCredentials.some(c => c.hasTotp)) return;

  activeTotpInterval = setInterval(() => {
    const totpItems = savedCredentials.filter(c => c.hasTotp);
    if (totpItems.length === 0) return;

    const windowStart = Math.floor(Date.now() / 30000);
    const remaining = getTOTPSecondsRemaining();

    for (const item of totpItems) {
      const timerEl = findCard(item.id)?.querySelector('.totp-timer');
      if (timerEl) timerEl.textContent = `${remaining}s`;
    }

    // Refresh on window rollover, or if a backgrounded tab missed the rollover
    if (remaining === 30 || totpItems.some(item => item.totpWindow !== windowStart)) refreshTotpCodes();
  }, 1000);
}

// Export the vault (LIST_ALL result) as JSON into the textarea
function exportVault() {
  const dump = savedCredentials.map(({ hostname, username, password, totpSecret }) => ({
    hostname, username, password, totpSecret
  }));
  exportArea.value = JSON.stringify(dump, null, 2);
}

// Toggle the shared textarea between hidden / read-only export / editable import
function setBackupMode(mode) {
  if (backupMode === mode) mode = null;
  backupMode = mode;

  if (mode === 'export') {
    exportVault();
    exportArea.readOnly = true;
    exportArea.hidden = false;
    exportArea.select();
  } else if (mode === 'import') {
    exportArea.value = '';
    exportArea.readOnly = false;
    exportArea.hidden = false;
    exportArea.focus();
  } else {
    exportArea.hidden = true;
  }
  exportBtn.textContent = mode === 'export' ? 'Close' : 'Export';
  importBtn.textContent = mode === 'import' ? 'Close' : 'Import';
  importGoRow.hidden = mode !== 'import';
}

// Add one credential via the existing worker action; resolves to true on success
function addCredential(entry) {
  return new Promise((resolve) => {
    chrome.runtime.sendMessage({
      action: 'ADD_CREDENTIAL',
      payload: {
        hostname: entry.hostname,
        username: entry.username,
        password: entry.password,
        totpSecret: entry.totpSecret
      }
    }, (response) => {
      resolve(!chrome.runtime.lastError && !!response?.success);
    });
  });
}

// Import a JSON array from the textarea, one ADD_CREDENTIAL at a time
async function importVault() {
  let parsed;
  try {
    parsed = JSON.parse(exportArea.value);
  } catch {
    showStatus('Import failed: invalid JSON.', true);
    return;
  }
  if (!Array.isArray(parsed)) {
    showStatus('Import failed: expected a JSON array.', true);
    return;
  }

  const entries = parsed.filter(e => e && typeof e === 'object');
  if (entries.length === 0) {
    showStatus('Import failed: no entries found.', true);
    return;
  }

  importGoBtn.disabled = true;
  let ok = 0;
  for (const entry of entries) {
    if (await addCredential(entry)) ok++;
  }
  importGoBtn.disabled = false;
  const failed = entries.length - ok;
  loadSavedCredentials();
  if (failed === 0) setBackupMode('import'); // toggle the box back closed
  showStatus(`Imported ${ok} credential(s)${failed ? `, ${failed} failed` : ''}.`, failed > 0);
}

// Load all credentials from service worker
function loadSavedCredentials() {
  chrome.runtime.sendMessage({ action: 'LIST_ALL' }, (response) => {
    if (chrome.runtime.lastError || !response?.success) {
      const msg = chrome.runtime.lastError?.message || response?.error || 'Failed to load saved credentials.';
      credentialsList.innerHTML = `<div class="empty-state">${escapeHtml(msg)}</div>`;
      showStatus(msg, true);
      return;
    }
    renderCredentials(response.credentials);
    startTotpLiveUpdater();
  });
}

// Password Visibility Toggle in Add Form
toggleFormPassBtn.addEventListener('click', () => {
  const isPass = passwordInput.type === 'password';
  passwordInput.type = isPass ? 'text' : 'password';
  toggleFormPassBtn.textContent = isPass ? 'Hide' : 'Show';
});

// Generate Random Password
genPassBtn.addEventListener('click', () => {
  passwordInput.value = generateRandomPassword(20);
  passwordInput.type = 'text';
  toggleFormPassBtn.textContent = 'Hide';
});

// Backup: export / import toggles
exportBtn.addEventListener('click', () => setBackupMode('export'));
importBtn.addEventListener('click', () => setBackupMode('import'));
importGoBtn.addEventListener('click', importVault);

// Add Credential Form Submission
addForm.addEventListener('submit', (e) => {
  e.preventDefault();

  const hostname = domainInput.value.trim();
  const username = usernameInput.value.trim();
  const password = passwordInput.value;
  const totpSecret = totpInput.value.trim();

  if (!hostname) {
    showStatus('Domain is required', true);
    return;
  }
  if (!username && !password && !totpSecret) {
    showStatus('At least one of username, password, or TOTP secret is required', true);
    return;
  }

  chrome.runtime.sendMessage({
    action: 'ADD_CREDENTIAL',
    payload: {
      hostname,
      username,
      password,
      totpSecret
    }
  }, (response) => {
    if (chrome.runtime.lastError) {
      showStatus('Failed to communicate with service worker', true);
      return;
    }

    if (response && response.success) {
      showStatus('Credential saved securely!');
      domainInput.value = '';
      usernameInput.value = '';
      passwordInput.value = '';
      totpInput.value = '';
      passwordInput.type = 'password';
      toggleFormPassBtn.textContent = 'Show';

      loadSavedCredentials();
    } else {
      showStatus(response?.error || 'Failed to save credential', true);
    }
  });
});

// Cleanup on unload
window.addEventListener('unload', () => {
  if (activeTotpInterval) clearInterval(activeTotpInterval);
});

// Initial load
loadSavedCredentials();
